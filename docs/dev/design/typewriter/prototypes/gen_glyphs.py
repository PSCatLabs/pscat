"""Generate twglyphs.ps: a monospace face's printable-ASCII outlines as
PostScript path data, for the #210 prototype (tw_proto.ps).

    python3 docs/dev/design/typewriter/prototypes/gen_glyphs.py [FONT.ttf]

FONT.ttf defaults to fonts/LiberationMono-Regular.ttf, so the script runs from
a bare checkout. The design (docs/dev/design/TYPEWRITER.md section 2) chose Courier Prime
(github.com/google/fonts, ofl/courierprime/CourierPrime-Regular.ttf, SIL OFL
1.1); prototype_vs_real.png was rendered from it. Output is derived font
software under the source's licence (OFL 1.1 for both; Liberation reserves the
names "Liberation", "Arimo", "Tinos" and "Cousine"), so twglyphs.ps is
generated, not committed (.gitignore).

Each glyph becomes TWG code [ {outer contours} {counter contours} ] put, in
1000 units per em. Outer contours and counters are told apart by winding:
TrueType draws outer contours clockwise. Composite glyphs are decomposed.
Integer keys use put, not def: pscat's def rejects them (#338).
"""
import os
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
import sys
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "fonts", "LiberationMono-Regular.ttf")
font = TTFont(SRC)
gs = font.getGlyphSet()
cmap = font.getBestCmap()
scale = 1000.0 / font["head"].unitsPerEm


def n(v):
    return f"{v * scale:.0f}"


def contours(name):
    pen = DecomposingRecordingPen(gs)
    gs[name].draw(pen)
    out, cur, start, pts = [], [], None, []
    last = None
    for op, args in pen.value:
        if op == "moveTo":
            cur, pts = [f"{n(args[0][0])} {n(args[0][1])} moveto"], [args[0]]
            last = start = args[0]
        elif op == "lineTo":
            cur.append(f"{n(args[0][0])} {n(args[0][1])} lineto")
            pts.append(args[0]); last = args[0]
        elif op == "qCurveTo":
            # expand the implied on-curve points, then raise each quadratic to a cubic
            offs = list(args[:-1]); end = args[-1]
            seq = []
            for i, q in enumerate(offs):
                nxt = end if i == len(offs) - 1 else ((q[0] + offs[i + 1][0]) / 2, (q[1] + offs[i + 1][1]) / 2)
                seq.append((q, nxt))
            for q, e in seq:
                c1 = (last[0] + 2 / 3 * (q[0] - last[0]), last[1] + 2 / 3 * (q[1] - last[1]))
                c2 = (e[0] + 2 / 3 * (q[0] - e[0]), e[1] + 2 / 3 * (q[1] - e[1]))
                cur.append(f"{n(c1[0])} {n(c1[1])} {n(c2[0])} {n(c2[1])} {n(e[0])} {n(e[1])} curveto")
                pts.append(e); last = e
        elif op == "curveTo":
            c1, c2, e = args
            cur.append(f"{n(c1[0])} {n(c1[1])} {n(c2[0])} {n(c2[1])} {n(e[0])} {n(e[1])} curveto")
            pts.append(e); last = e
        elif op in ("closePath", "endPath"):
            cur.append("closepath")
            area = sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1]
                       for i in range(len(pts))) / 2
            out.append((area, " ".join(cur)))
    return out


lines = ["% twglyphs.ps: generated by gen_glyphs.py from Liberation Mono (SIL OFL 1.1).",
         "% Derived outlines; OFL 1.1 applies. Not a Reserved Font Name.",
         "/TWG 128 dict def"]
for code in range(32, 127):
    name = cmap.get(code)
    if name is None:
        continue
    cs = contours(name)
    outer = " ".join(p for a, p in cs if a < 0)     # clockwise in y-up = outer
    inner = " ".join(p for a, p in cs if a >= 0)
    lines.append(f"TWG {code} [{{{outer}}} {{{inner}}}] put")
with open(os.path.join(HERE, "twglyphs.ps"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote twglyphs.ps,", os.path.getsize(os.path.join(HERE, "twglyphs.ps")), "bytes")
