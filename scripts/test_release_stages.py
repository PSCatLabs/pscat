def make_crate(path, commit=COMMIT, extra=b"", mtime=0, generated=b"", orig=True, readme=README, version=VERSION):
    """A minimal .crate: pscat-<ver>/{Cargo.toml.orig, Cargo.toml (cargo's
    normalized copy), src/lib.rs, README.md, .cargo_vcs_info.json}. `extra`
    changes the source manifest; `generated` only cargo's normalized one."""
    manifest = b'[package]\nname = "pscat"\nversion = "' + version.encode() + b'"\n'
    files = {
        f"pscat-{version}/Cargo.toml": b"# generated by cargo\n" + manifest + generated,
        f"pscat-{version}/src/lib.rs": b"pub fn f() {}\n",
        f"pscat-{version}/README.md": readme,
    }
    if orig:
        files[f"pscat-{version}/Cargo.toml.orig"] = manifest + extra
    if commit is not None:
        files[f"pscat-{version}/.cargo_vcs_info.json"] = json.dumps(
            {"git": {"sha1": commit}, "path_in_vcs": ""}).encode()
    with tarfile.open(path, "w:gz") as tar:
        for name, data in sorted(files.items()):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mtime = mtime
            tar.addfile(info, io.BytesIO(data))


def make_npm_tarball(path, name="pscat-wasm", version=VERSION, extra=b""):
    """A minimal npm tarball: package/package.json (+ `extra` in a file)."""
    files = {"package/package.json": json.dumps({"name": name, "version": version}).encode(),
             "package/index.js": b"export {};\n" + extra}
    with tarfile.open(path, "w:gz") as tar:
        for n, data in sorted(files.items()):
            info = tarfile.TarInfo(n)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))


def make_dist(tmp, commit=COMMIT, payload=b"binary", version=VERSION):
    dist = os.path.join(tmp, "dist")
    os.makedirs(dist, exist_ok=True)
    for target, ext in (("aarch64-apple-darwin", ".tar.gz"), ("x86_64-pc-windows-msvc", ".zip")):
        with open(os.path.join(dist, f"pscat-{version}-{target}{ext}"), "wb") as f:
            f.write(payload + target.encode())
    crate = os.path.join(tmp, f"pscat-{version}.crate")
    make_crate(crate, commit, version=version)
    rs.write_manifest(rs.build_manifest(f"v{version}", commit, dist, crate), dist)
    return dist, crate


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="release-test-")
        self.repo = os.path.join(self.tmp, "repo")
        os.makedirs(self.repo)
        self.dist, self.crate = make_dist(self.tmp)
        self.m = rs.load_manifest(self.dist)
        self.fake = rs.Fake(os.path.join(self.tmp, "fake"))
        self.fake.set_tag(TAG, COMMIT)

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def ctx(self, plan=False, crate=None):
        f = self.fake
        return rs.Ctx(self.m, self.dist, crate or self.crate, self.repo, f, rs.FakeCrates(f), rs.FakeNpm(f), plan,
                      rs.FakeRegistry(f))

    def run_all(self, plan=False, crate=None):
        st, res = rs.run_stages(self.ctx(plan, crate), list(rs.STAGES))
        return st, {r["stage"]: r["result"] for r in res}, res


class Manifest(Base):
    def test_manifest_records_provenance_and_digests(self):
        self.assertEqual(self.m["tag"], TAG)
        self.assertEqual(self.m["commit"], COMMIT)
        self.assertEqual([a["name"] for a in self.m["assets"]],
                         [f"pscat-{VERSION}-aarch64-apple-darwin.tar.gz", f"pscat-{VERSION}-x86_64-pc-windows-msvc.zip"])
        with open(os.path.join(self.dist, rs.SUMS_NAME), encoding="utf-8") as f:
            self.assertEqual(f.read(), rs.sums_text(self.m["assets"]))

    def test_manifest_refuses_a_crate_from_another_commit(self):
        other = os.path.join(self.tmp, "other.crate")
        make_crate(other, commit="f" * 40)
        with self.assertRaises(SystemExit):
            rs.build_manifest(TAG, COMMIT, self.dist, other)

    def test_manifest_refuses_a_bad_tag(self):
        with self.assertRaises(SystemExit):
            rs.build_manifest("9.8.7", COMMIT, self.dist, self.crate)

    def test_uploaded_crate_path_prefers_cargo_publish_tmp_crate(self):
        with tempfile.TemporaryDirectory() as root:
            pkg = os.path.join(root, "target", "package")
            os.makedirs(os.path.join(pkg, "tmp-crate"))
            with self.assertRaises(rs.StageError):
                rs.uploaded_crate_path(root, "pscat-1.0.0.crate")
            open(os.path.join(pkg, "pscat-1.0.0.crate"), "wb").close()
            self.assertEqual(rs.uploaded_crate_path(root, "pscat-1.0.0.crate"),
                             os.path.join(pkg, "pscat-1.0.0.crate"))
            open(os.path.join(pkg, "tmp-crate", "pscat-1.0.0.crate"), "wb").close()
            self.assertEqual(rs.uploaded_crate_path(root, "pscat-1.0.0.crate"),
                             os.path.join(pkg, "tmp-crate", "pscat-1.0.0.crate"))

    def test_crate_identity_ignores_tar_metadata(self):
        a = os.path.join(self.tmp, "a.crate")
        b = os.path.join(self.tmp, "b.crate")
        make_crate(a, mtime=0)
        make_crate(b, mtime=123456)
        self.assertNotEqual(rs.sha256_file(a), rs.sha256_file(b))
        self.assertEqual(rs.crate_identity(a), rs.crate_identity(b))


class EndToEnd(Base):
    def test_plan_then_publish_then_rerun(self):
        st, r, _ = self.run_all(plan=True)
        self.assertEqual(st, rs.EXIT_OK)
        self.assertEqual(r, {"draft": "would create", "crates": "would publish", "npm": "disabled",
                             "publish": "would publish", "plugin": "disabled", "registry": "disabled"})
        self.assertEqual(self.fake.events(), [])

        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK)
        self.assertEqual(r["draft"], "published")
        self.assertEqual(r["crates"], "published")
        self.assertEqual(r["publish"], "published")
        names = [e.split(" ", 1)[1] for e in self.fake.events() if e.startswith("github.upload")]
        self.assertEqual(names[-1], rs.MANIFEST_NAME, "the manifest goes up last")
        rel = self.fake.releases(TAG)
        self.assertEqual(len(rel), 1)
        self.assertFalse(rel[0]["draft"])

        events = self.fake.events()
        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK)
        self.assertEqual(self.fake.events(), events, "a re-run changes nothing")
        self.assertEqual(r["draft"], "skipped")
        self.assertEqual(r["crates"], "skipped")
        self.assertEqual(r["publish"], "skipped")

    def test_report(self):
        st, _, res = self.run_all()
        rep = rs.report(self.m, res, st, False, "fake")
        md = rs.report_markdown(rep)
        self.assertIn("| crates | published |", md)
        self.assertIn(self.m["assets"][0]["sha256"], md)
        self.assertEqual(rep["status"], "ok")


class PartialFailure(Base):
    def _fail(self, op):
        with open(os.path.join(self.fake.root, "fail-once"), "w", encoding="utf-8") as f:
            f.write(op)

    def test_crates_succeeds_then_publish_fails_then_rerun(self):
        self._fail("github.publish")
        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_ERROR)
        self.assertEqual(r["crates"], "published")
        self.assertEqual(r["publish"], "error")
        self.assertEqual(r["plugin"], "not run")

        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK)
        self.assertEqual(r["crates"], "skipped")
        self.assertEqual(r["publish"], "published")
        self.assertEqual(len([e for e in self.fake.events() if e.startswith("crates.publish")]), 1)

    def test_interrupted_upload_resumes_the_draft(self):
        # The draft exists with the first archive only (the job died mid-upload).
        rid = self.fake.create_draft(TAG, "x", "x")
        first = self.m["assets"][0]["name"]
        self.fake.upload(rid, os.path.join(self.dist, first), first)
        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK, r)
        rel = self.fake.releases(TAG)[0]
        self.assertEqual(sorted(a["name"] for a in rel["assets"]), sorted(rs.release_files(self.m)))

    def test_rebuilt_artifacts_adopt_a_complete_draft(self):
        # Run 1 made the whole draft, then the job failed before crates.io.
        self._fail("crates.publish")
        st, r, _ = self.run_all()
        self.assertEqual((st, r["draft"], r["crates"]), (rs.EXIT_ERROR, "published", "error"))
        # Run 2 rebuilt the binaries from the same commit: different bytes.
        shutil.rmtree(self.dist)
        self.dist, _ = make_dist(self.tmp, payload=b"rebuilt")
        self.m = rs.load_manifest(self.dist)
        st, r, _ = self.run_all()
        self.assertEqual(st, rs.EXIT_OK, r)
        self.assertEqual(r["draft"], "skipped")

    def test_crate_from_another_cargo_version_matches(self):
        # cargo's normalized Cargo.toml differs, the source is the same.
        self.fake.publish_crate(self.crate)
        other = os.path.join(self.tmp, "newer-cargo", f"pscat-{VERSION}.crate")
        os.makedirs(os.path.dirname(other))
        make_crate(other, generated=b"autolib = false\n")
        st, r, res = self.run_all(crate=other)
        self.assertEqual(st, rs.EXIT_OK, res)
        self.assertEqual(r["crates"], "skipped")

    def test_crates_identity_from_a_repackaged_crate(self):
        # Same commit and contents, packaged again (different tar mtimes).
        self.fake.publish_crate(self.crate)
        again = os.path.join(self.tmp, "again", f"pscat-{VERSION}.crate")
        os.makedirs(os.path.dirname(again))
        make_crate(again, mtime=99)
        st, r, res = self.run_all(crate=again)
        self.assertEqual(st, rs.EXIT_OK, res)
        self.assertEqual(r["crates"], "skipped")


