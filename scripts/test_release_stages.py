@unittest.skipUnless(shutil.which("git-cliff"), "git-cliff not installed")
class ReleaseScript(unittest.TestCase):
    """scripts/release.sh --no-push in a scratch clone of this repo."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="release-sh-")
        self.clone = os.path.join(self.tmp, "clone")
        subprocess.run(["git", "clone", "--quiet", "--no-local", rs.ROOT, self.clone], check=True)
        # Work on whatever is checked out here (the PR's tree), as `main`.
        head = subprocess.run(["git", "-C", rs.ROOT, "rev-parse", "HEAD"], capture_output=True, text=True,
                              check=True).stdout.strip()
        subprocess.run(["git", "-C", self.clone, "checkout", "--quiet", "-B", "main", head], check=True)
        for name in ("scripts/release.sh", "scripts/release_stages.py", "cliff.toml"):
            shutil.copyfile(os.path.join(rs.ROOT, name), os.path.join(self.clone, name))
        subprocess.run(["git", "-C", self.clone, "-c", "user.name=t", "-c", "user.email=t@example.com",
                        "commit", "--quiet", "--allow-empty", "-am", "test: the tree under test"], check=True)

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def release(self, *args):
        env = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@example.com",
                   GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@example.com", RELEASE_SKIP_FETCH="1")
        return subprocess.run(["bash", "scripts/release.sh", *args], cwd=self.clone, env=env,
                              capture_output=True, text=True)

    def test_refuses_while_unpinned(self):
        if rs.pinned_index(self.clone) is not None:
            self.skipTest("the font index is pinned")
        p = self.release("99.0.0", "--no-push")
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("PINNED_INDEX = None", p.stderr)

    def test_bumps_versions_and_writes_the_changelog(self):
        p = self.release("99.0.0", "--no-push", "--allow-unpinned")
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)
        self.assertEqual(rs.cargo_version(self.clone), "99.0.0")
        with open(os.path.join(self.clone, "Cargo.lock"), encoding="utf-8") as f:
            self.assertIn('name = "pscat"\nversion = "99.0.0"', f.read())
        with open(os.path.join(self.clone, "npm", "package.json"), encoding="utf-8") as f:
            self.assertEqual(json.load(f)["version"], "99.0.0")
        changed = subprocess.run(["git", "-C", self.clone, "show", "--name-only", "--format=", "HEAD"],
                                 capture_output=True, text=True, check=True).stdout.split()
        self.assertIn("npm/package.json", changed)
        with open(os.path.join(self.clone, "CHANGELOG.md"), encoding="utf-8") as f:
            text = f.read()
        self.assertIn("## [99.0.0]", text)
        branch = subprocess.run(["git", "-C", self.clone, "branch", "--show-current"], capture_output=True,
                                text=True).stdout.strip()
        self.assertEqual(branch, "release/v99.0.0")
        msg = subprocess.run(["git", "-C", self.clone, "log", "-1", "--format=%s"], capture_output=True,
                             text=True).stdout.strip()
        self.assertEqual(msg, "release: 99.0.0")

    def test_refuses_a_version_that_is_not_newer(self):
        p = self.release("0.0.1", "--no-push", "--allow-unpinned")
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("not newer", p.stderr)

    def git(self, *args):
        return subprocess.run(["git", "-C", self.clone, *args], capture_output=True, text=True,
                              check=True).stdout.strip()

    def test_release_candidate_then_release(self):
        before = self.git("show", "HEAD:CHANGELOG.md") if os.path.exists(
            os.path.join(self.clone, "CHANGELOG.md")) else None
        p = self.release("99.0.0-rc.1", "--no-push", "--allow-unpinned")
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)
        self.assertEqual(rs.cargo_version(self.clone), "99.0.0-rc.1")
        with open(os.path.join(self.clone, "npm", "package.json"), encoding="utf-8") as f:
            self.assertEqual(json.load(f)["version"], "99.0.0-rc.1")
        changed = self.git("show", "--name-only", "--format=", "HEAD").split()
        self.assertNotIn("CHANGELOG.md", changed)
        if before is not None:
            self.assertEqual(self.git("show", "HEAD:CHANGELOG.md"), before)
        self.assertEqual(self.git("branch", "--show-current"), "release/v99.0.0-rc.1")
        self.assertEqual(self.git("log", "-1", "--format=%s"), "release: 99.0.0-rc.1")
        # Merged: main now carries the rc. The same rc again is not newer;
        # the release it is a candidate for is.
        self.git("checkout", "--quiet", "main")
        self.git("merge", "--quiet", "--ff-only", "release/v99.0.0-rc.1")
        p = self.release("99.0.0-rc.1", "--no-push", "--allow-unpinned")
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("not newer", p.stderr)
        p = self.release("99.0.0", "--no-push", "--allow-unpinned")
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)
        self.assertEqual(rs.cargo_version(self.clone), "99.0.0")
        with open(os.path.join(self.clone, "CHANGELOG.md"), encoding="utf-8") as f:
            self.assertIn("## [99.0.0]", f.read())

    def test_refuses_a_non_rc_prerelease(self):
        p = self.release("99.0.0-beta.1", "--no-push", "--allow-unpinned")
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("is not X.Y.Z or X.Y.Z-rc.N", p.stderr)

    def test_refuses_a_dirty_tree(self):
        with open(os.path.join(self.clone, "README.md"), "a", encoding="utf-8") as f:
            f.write("dirty\n")
        p = self.release("99.0.0", "--no-push", "--allow-unpinned")
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("uncommitted", p.stderr)


