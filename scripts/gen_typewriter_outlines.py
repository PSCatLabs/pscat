#!/usr/bin/env python3
"""Generate lib/typewriter_outlines.ps: Courier Prime's printable-ASCII
outlines as PostScript path data, for the /Typewriter font (lib/typewriter.ps,
issue #211, design docs/TYPEWRITER.md section 2).

    python3 scripts/gen_typewriter_outlines.py

Needs fontTools (pip install fonttools). Reads
fonts/catalog/CourierPrime/CourierPrime-Regular.ttf (SIL OFL 1.1, from
github.com/google/fonts, ofl/courierprime) and overwrites
lib/typewriter_outlines.ps. The output is deterministic, so a re-run on an
unchanged TTF leaves git clean.

Each glyph becomes `TWOutlines code [ {outer contours} {counter contours} ] put`
in 1000 units per em. Outer contours and counters are told apart by winding:
TrueType draws outer contours clockwise. Keeping them apart lets the ink model
(#212) fill a clogged counter on its own; filled together under the nonzero
rule they draw the plain glyph. Composite glyphs are decomposed. Quadratic
segments are raised to cubics exactly. Integer keys use put, not def: pscat's
def rejects them (#338). The procedures are bound as they are read, so gs does
not look up moveto/curveto by name at every strike (notes/307).
"""
import os
import sys

from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "fonts", "catalog", "CourierPrime", "CourierPrime-Regular.ttf")
OUT = os.path.join(ROOT, "lib", "typewriter_outlines.ps")

font = TTFont(SRC)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
scale = 1000.0 / font["head"].unitsPerEm


def n(v):
    # "-0" and "0" must print the same, or a re-run on another platform
    # could churn the file.
    s = f"{v * scale:.0f}"
    return "0" if s == "-0" else s


def contours(name):
    """[(signed area, path text)] for each closed contour of glyph `name`."""
    pen = DecomposingRecordingPen(glyphs)
    glyphs[name].draw(pen)
    out, cur, pts, last = [], [], [], None
    for op, args in pen.value:
        if op == "moveTo":
            cur, pts = [f"{n(args[0][0])} {n(args[0][1])} moveto"], [args[0]]
            last = args[0]
        elif op == "lineTo":
            cur.append(f"{n(args[0][0])} {n(args[0][1])} lineto")
            pts.append(args[0])
            last = args[0]
        elif op == "qCurveTo":
            if args[-1] is None:
                sys.exit(f"{name}: an all-off-curve contour; teach the generator to close it")
            # Expand the implied on-curve midpoints, then raise each
            # quadratic to the cubic with the same curve.
            offs, end = list(args[:-1]), args[-1]
            for i, q in enumerate(offs):
                e = end if i == len(offs) - 1 else ((q[0] + offs[i + 1][0]) / 2, (q[1] + offs[i + 1][1]) / 2)
                c1 = (last[0] + 2 / 3 * (q[0] - last[0]), last[1] + 2 / 3 * (q[1] - last[1]))
                c2 = (e[0] + 2 / 3 * (q[0] - e[0]), e[1] + 2 / 3 * (q[1] - e[1]))
                cur.append(f"{n(c1[0])} {n(c1[1])} {n(c2[0])} {n(c2[1])} {n(e[0])} {n(e[1])} curveto")
                pts.append(e)
                last = e
        elif op == "curveTo":
            c1, c2, e = args
            cur.append(f"{n(c1[0])} {n(c1[1])} {n(c2[0])} {n(c2[1])} {n(e[0])} {n(e[1])} curveto")
            pts.append(e)
            last = e
        elif op in ("closePath", "endPath"):
            cur.append("closepath")
            area = sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1]
                       for i in range(len(pts))) / 2
            out.append((area, " ".join(cur)))
    return out


hmtx = font["hmtx"]
advances = {round(hmtx[cmap[c]][0] * scale) for c in range(32, 127)}
if advances != {600}:
    sys.exit(f"expected a 600-unit monospace advance, got {sorted(advances)}")

lines = [
    "%!PS-Adobe-3.0",
    "%%Title: typewriter_outlines.ps -- Courier Prime outlines for /Typewriter",
    "%%EndComments",
    "",
    "% GENERATED by scripts/gen_typewriter_outlines.py from",
    "% fonts/catalog/CourierPrime/CourierPrime-Regular.ttf. Do not edit by hand.",
    "%",
    "% Copyright 2015 The Courier Prime Project Authors",
    "% (https://github.com/quoteunquoteapps/CourierPrime).",
    "% These outlines are derived from Courier Prime, which is licensed under",
    "% the SIL Open Font License, Version 1.1; this file is therefore also",
    "% licensed under the OFL 1.1 (fonts/catalog/CourierPrime/OFL.txt, or",
    "% https://openfontlicense.org). Courier Prime has no Reserved Font Name.",
    "%",
    "% TWOutlines maps each printable ASCII code (32-126) to",
    "% [ {outer contours} {counter contours} ] in 1000 units per em, on a",
    "% 600-unit advance. lib/typewriter.ps draws them; it needs this file",
    "% run first (its @requires line).",
    "",
    "% @internal",
    "/TWOutlines << >> def",
]
for code in range(32, 127):
    cs = contours(cmap[code])
    outer = " ".join(p for a, p in cs if a < 0)  # clockwise in y-up = outer
    inner = " ".join(p for a, p in cs if a >= 0)
    lines.append(f"TWOutlines {code} [{{{outer}}} bind {{{inner}}} bind] put")
with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {os.path.relpath(OUT, ROOT)}, {os.path.getsize(OUT)} bytes")
